export const PROVISIONER_LABELS: Record<string, string> = {
  barebones: "Barebones",
  default: "Default",
  reconftw: "ReconFTW",
  extras: "Extras",
};

/** Returns true if module is likely available for the given provisioner image. */
export function isModuleAvailable(
  moduleName: string,
  provisioner: string,
): boolean {
  if (!provisioner || provisioner === "unknown") return true;
  const tools = PROVISIONER_TOOLS[provisioner.toLowerCase()] ?? [];
  if (!tools.length) return true;
  const mod = moduleName.toLowerCase();
  return tools.some((tool) => mod.includes(tool) || tool.includes(mod));
}

/** Finds which provisioner images include this module (for tooltip text). */
export function getRequiredProvisioners(moduleName: string): string[] {
  return Object.entries(PROVISIONER_TOOLS)
    .filter(([, tools]) => {
      const mod = moduleName.toLowerCase();
      return tools.some((t) => mod.includes(t) || t.includes(mod));
    })
    .map(([key]) => PROVISIONER_LABELS[key] ?? key);
}
